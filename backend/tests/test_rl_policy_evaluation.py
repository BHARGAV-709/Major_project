import unittest
import numpy as np
from app.workload import WorkloadGenerator
from app.simulation.resource_manager import ClusterResourceState
from app.algorithms.reinforcement_learning import QLearningScheduler, DQNScheduler
from app.evaluation.metrics import PerformanceEvaluator

class TestRLPolicyEvaluation(unittest.TestCase):

    def setUp(self):
        self.cluster = ClusterResourceState(total_cpu=40, total_memory_mb=262144.0, total_gpu=8)
        self.jobs = WorkloadGenerator.generate_scenario("LIGHT", num_jobs=10, seed=42)

    def test_q_learning_policy_evaluation_deterministic(self):
        """Verify Q-Learning evaluate_policy executes greedily (deterministic) and returns valid schedule and cumulative reward."""
        ql = QLearningScheduler(episodes=15)
        train_res = ql.train(self.jobs, self.cluster)
        
        # Test separate evaluate_policy method
        eval_completed, eval_reward = ql.evaluate_policy(self.jobs, self.cluster)
        self.assertIsInstance(eval_completed, list)
        self.assertGreater(len(eval_completed), 0)
        self.assertIsInstance(eval_reward, float)
        
        # Verify returned training schedule matches evaluation output or valid fallback
        self.assertEqual(len(train_res["best_completed_jobs"]), len(self.jobs))
        self.assertIn("eval_reward", train_res)
        self.assertIn("history", train_res)

        # Verify job validity
        for job in eval_completed:
            self.assertIsNotNone(job.start_time)
            self.assertIsNotNone(job.finish_time)
            self.assertGreaterEqual(job.finish_time, job.start_time)

    def test_dqn_policy_evaluation_deterministic(self):
        """Verify DQN evaluate_policy executes greedily (deterministic) and returns valid schedule and cumulative reward."""
        dqn = DQNScheduler(episodes=15)
        train_res = dqn.train(self.jobs, self.cluster)

        # Test separate evaluate_policy method
        eval_completed, eval_reward = dqn.evaluate_policy(self.jobs, self.cluster)
        self.assertIsInstance(eval_completed, list)
        self.assertGreater(len(eval_completed), 0)
        self.assertIsInstance(eval_reward, float)

        # Verify returned training schedule matches evaluation output or valid fallback
        self.assertEqual(len(train_res["best_completed_jobs"]), len(self.jobs))
        self.assertIn("eval_reward", train_res)
        self.assertIn("history", train_res)

        # Verify job validity
        for job in eval_completed:
            self.assertIsNotNone(job.start_time)
            self.assertIsNotNone(job.finish_time)
            self.assertGreaterEqual(job.finish_time, job.start_time)

    def test_evaluate_action_selection_mode(self):
        """Verify select_action with evaluate=True operates greedily without epsilon exploration."""
        ql = QLearningScheduler(episodes=5, epsilon_start=1.0)
        state = np.zeros(6, dtype=np.float32)
        discrete_state = ql._discretize_state(state)
        ql.q_table[discrete_state] = np.array([0.1, 0.9, 0.2, 0.0, 0.0, 0.0], dtype=np.float32)
        
        # Epsilon is 1.0, but evaluate=True should strictly pick argmax (action 1)
        action = ql.select_action(state, evaluate=True)
        self.assertEqual(action, 1)

        dqn = DQNScheduler(episodes=5, epsilon_start=1.0)
        dqn.epsilon = 1.0
        # With evaluate=True, select_action must run policy_net argmax, never random
        action_dqn = dqn.select_action(state, evaluate=True)
        self.assertIsInstance(action_dqn, int)
        self.assertIn(action_dqn, range(dqn.action_dim))

    def test_schedule_validity_metrics(self):
        """Verify that schedules generated by both RL algorithms produce valid performance metrics."""
        cluster_config = {"cpu_cores": 40, "memory_gb": 256, "gpu_units": 8}
        
        for SchedulerClass in [QLearningScheduler, DQNScheduler]:
            scheduler = SchedulerClass(episodes=10)
            res = scheduler.train(self.jobs, self.cluster)
            
            schedule_dicts = [
                {
                    "job_id": j.job_id,
                    "finish_time": j.finish_time,
                    "waiting_time": j.waiting_time,
                    "cpu_cores": j.cpu_cores,
                    "memory_mb": j.memory_mb,
                    "gpu_units": j.gpu_units,
                    "runtime": j.runtime,
                    "sla_status": "VIOLATED" if j.sla_violated else "MET",
                    "deadline": j.deadline
                }
                for j in res["best_completed_jobs"]
            ]
            
            metrics = PerformanceEvaluator.calculate_metrics(schedule_dicts, cluster_config)
            self.assertGreater(metrics["makespan"], 0.0)
            self.assertGreaterEqual(metrics["overall_utilization"], 0.0)
            self.assertGreaterEqual(metrics["efficiency_score"], 0.0)

if __name__ == "__main__":
    unittest.main()

